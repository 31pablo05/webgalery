function foto(archivo, ancho, alto, alt = '') {
	const nombre = String(archivo).replace(/\.jpg$/i, '')
	const id = `image-demo-${nombre}-${ancho}x${alto}-jpg`
	return {
		alt,
		asset: {
			_type: 'reference',
			_ref: id,
			_id: id,
			metadata: { dimensions: { width: ancho, height: alto } },
		},
	}
}

function parrafo(partes) {
	return {
		_type: 'block',
		style: 'normal',
		children: partes.map((parte) => ({
			_type: 'span',
			text: parte.texto,
			marks: parte.fuerte ? ['strong'] : [],
		})),
	}
}

function obra({
	titulo,
	slug,
	anio,
	tecnica,
	dimensiones,
	estado,
	categoria,
	serie = '',
	archivo,
	ancho,
	alto,
	destacada = false,
	orden,
	descripcion,
	extras = [],
}) {
	return {
		_type: 'obra',
		titulo,
		slug,
		anio,
		tecnica,
		dimensiones,
		estado,
		categoria,
		serie,
		descripcionCorta: descripcion,
		destacadaEnInicio: destacada,
		ordenGaleria: orden,
		imagenPrincipal: foto(archivo, ancho, alto, titulo),
		imagenesAdicionales: extras,
	}
}

