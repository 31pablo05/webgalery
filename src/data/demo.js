function proyecto({
	titulo,
	anio,
	duracion,
	descripcion,
	vimeo,
	categoria,
	destacado = false,
	enInicio = false,
	archivo,
}) {
	return {
		_id: `demo-${titulo.toLowerCase().replace(/\s+/g, '-')}`,
		_type: 'proyectoAudiovisual',
		titulo,
		anio,
		duracion,
		descripcionCorta: descripcion,
		linkVimeo: vimeo,
		categoria,
		destacado,
		mostrarEnInicio: enInicio,
		miniatura: foto(archivo, 1600, 900, titulo),
	}
}

